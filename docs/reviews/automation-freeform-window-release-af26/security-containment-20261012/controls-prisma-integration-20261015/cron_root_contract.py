"""Exact cron sources, separating generated Debian spool headers from installed body."""
import hashlib,re
from pathlib import Path
DEPLOY='/var/spool/cron/crontabs/deploy'
SYSTEM='/etc/cron.d/re7-converta-backup'
def spool_body(raw):
 lines=raw.splitlines(keepends=True)
 if len(lines)<3 or not lines[0].startswith('# DO NOT EDIT THIS FILE - edit the master and reinstall.') or not re.fullmatch(r'# \(.+ installed on .+\)\n',lines[1]) or not lines[2].startswith('# (Cron version -- '):raise RuntimeError('cron_spool_header_unrecognized')
 return ''.join(lines[3:])
def verify_cron_capture(root,current,baseline):
 root=Path(root);a={x['path']:x for x in current};b={x['path']:x for x in baseline}
 if len(a)!=len(current)or len(b)!=len(baseline)or set(a)!=set(b):raise RuntimeError('cron_source_population_changed')
 if DEPLOY not in a or SYSTEM not in a:raise RuntimeError('canonical_cron_source_missing')
 for path,e in a.items():
  raw=e['rawPrivate']
  if hashlib.sha256(raw.encode()).hexdigest()!=e['sha256']:raise RuntimeError('cron_capture_hash_invalid')
  if path==DEPLOY:
   expected=(root/'window/deploy.crontab.before').read_text()
   if spool_body(raw)!=expected or spool_body(b[path]['rawPrivate'])!=expected:raise RuntimeError('deploy_cron_functional_drift')
  elif path==SYSTEM:
   if raw!=(root/'window/re7-converta-backup.before').read_text()or e['sha256']!=b[path]['sha256']:raise RuntimeError('system_cron_functional_drift')
  elif e['sha256']!=b[path]['sha256']:raise RuntimeError('other_scheduled_source_changed')
 return {'deployBefore':True,'systemBefore':True,'otherCronReferencesUnchanged':True}
